import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const taskRoot = fileURLToPath(new URL("..", import.meta.url));
const releaseId = process.env.SMARTVIDEO_BETA_RELEASE_ID || "20261010.2";
assert.match(releaseId, /^\d{8}\.\d+$/);
const root = path.join(taskRoot, "artifacts", `smart-video-beta-${releaseId}`);
const plan = JSON.parse(readFileSync(path.join(root, "release-plan.json")));
assert.equal(plan.status, "published");
const home = path.join(root, "registry-home");
const codexHome = path.join(root, "codex-profile");
mkdirSync(home, { recursive: true });
mkdirSync(codexHome, { recursive: true });
const environment = Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith("SMARTVIDEO_") && !key.startsWith("FRAMEVIDEO_")));
Object.assign(environment, { CODEX_HOME: codexHome, SMARTVIDEO_HOME: home });
const codex = (args) => JSON.parse(execFileSync("codex", [...args, "--json"], { env: environment, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 }));
const market = codex(["plugin", "marketplace", "add", "JoggAI-Tech/jogg-skills", "--ref", plan.git_tag]);
const plugin = codex(["plugin", "add", `${plan.plugin_name}@${plan.marketplace}`]);
assert.equal(plugin.version, plan.plugin_version);
assert.equal(plugin.name, plan.plugin_name);
const skill = readFileSync(path.join(plugin.installedPath, "skills/smart-video/SKILL.md"), "utf8");
assert.ok(skill.includes('ask that user to reply "local" again.'));
const python = path.join(root, "smoke/venv", process.platform === "win32" ? "Scripts/python.exe" : "bin/python");
writeFileSync(path.join(home, "config.json"), JSON.stringify({ tools: { service_python: python }, testing: { in_memory_credential_store: true } }));
const launcher = path.join(plugin.installedPath, "scripts/launcher.mjs");
const output = execFileSync(process.execPath, [launcher, "bootstrap"], { env: environment, encoding: "utf8", maxBuffer: 8 * 1024 * 1024 });
assert.equal(JSON.parse(output).ready, true);
const active = JSON.parse(readFileSync(path.join(home, "active-runtime.json")));
assert.equal(active.version, plan.aggregate_version);
for (const pkg of plan.packages) assert.equal(JSON.parse(readFileSync(path.join(active.install_root, "node_modules", ...pkg.name.split("/"), "package.json"))).version, pkg.version);
const tts = JSON.parse(execFileSync(process.execPath, [launcher, "doctor", "--for", "local-tts", "--json"], { env: environment, encoding: "utf8" }));
const asr = JSON.parse(execFileSync(process.execPath, [launcher, "doctor", "--for", "local-asr", "--json"], { env: environment, encoding: "utf8" }));
assert.ok(tts.dependencies.some((item) => item.id === "edge_tts"));
assert.ok(asr.dependencies.some((item) => item.id === "faster_whisper"));
assert.ok(asr.dependencies.some((item) => item.id === "whisper-model"));
assert.ok(!tts.dependencies.some((item) => /whisper|bridge|vosk/.test(item.id)));
assert.ok(!asr.dependencies.some((item) => /edge|bridge|vosk/.test(item.id)));
const avatar = JSON.parse(execFileSync(process.execPath, [launcher, "doctor", "--for", "local-avatar", "--json"], { env: environment, encoding: "utf8" }));
const avatarGuidance = avatar.dependencies.find((item) => item.id === "avatar-resources").install_guidance;
assert.equal(avatarGuidance.preferred_action, "agent");
assert.equal(avatarGuidance.user_choices, undefined);
assert.deepEqual(avatarGuidance.command, ["resources", "install", "office-presenter", "--json"]);
writeFileSync(path.join(root, "published-verification.json"), `${JSON.stringify({ status: "passed", marketplace: market, plugin, npm_registry_bootstrap: true, exact_beta_versions: true, service_environment_ready: true, speech_preparation_on_demand: true, isolated_codex_profile: true }, null, 2)}\n`);
console.log("GitHub tag installation and npm registry bootstrap passed in an isolated Codex profile.");
